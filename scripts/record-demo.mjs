// Genuine live UI recording; server model calls incur usage.
// Never distribute RUN_DIR/.private (browser-session credentials).
import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
const out=process.env.RUN_DIR || path.resolve('demo/raw');
await fs.mkdir(out,{recursive:true});
const privateDir=path.join(out,'.private');
await fs.mkdir(privateDir,{recursive:true,mode:0o700});
const url=process.env.STAGE_URL || 'https://offload-eta.vercel.app';
const start=Date.now();
const logs=[]; const errors=[]; const requests=[];
async function mark(action,extra={}){const row={at:new Date().toISOString(),elapsedSeconds:Number(((Date.now()-start)/1000).toFixed(2)),action,...extra};logs.push(row);console.log(JSON.stringify(row));await fs.writeFile(path.join(out,'walkthrough-actions.json'),JSON.stringify({url,logs},null,2));}
const browser=await chromium.launch({channel:'chromium',headless:true});
const context=await browser.newContext({viewport:{width:1280,height:800},recordVideo:{dir:out,size:{width:1280,height:800}}});
const page=await context.newPage();page.setDefaultTimeout(30000);
page.on('console',msg=>{if(msg.type()==='error') errors.push({kind:'console',text:msg.text(),at:Date.now()-start})});
page.on('pageerror',err=>errors.push({kind:'pageerror',text:err.message,at:Date.now()-start}));
page.on('response',response=>{if(response.url().includes('/api/'))requests.push({url:response.url(),status:response.status(),at:Date.now()-start})});
page.on('requestfailed',request=>errors.push({kind:'requestfailed',url:request.url(),error:request.failure(),at:Date.now()-start}));
const video=page.video();
try{
 await page.goto(url,{waitUntil:'domcontentloaded'});
 await page.getByText('Live Meta API',{exact:true}).waitFor();
 await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='Try the demo item'&&!b.disabled));
 await fs.writeFile(path.join(privateDir,'browser-session.json'),JSON.stringify(await context.storageState()),{mode:0o600});
 await mark('fresh_live_session_ready',{title:await page.title()});
 await page.screenshot({path:path.join(out,'01-desktop-home.png'),fullPage:false});
 const sellResponse=page.waitForResponse(r=>r.url().endsWith('/api/sell')&&r.request().method()==='POST',{timeout:300000});
 await mark('sample_pipeline_started');
 await page.getByRole('button',{name:'Try the demo item',exact:true}).click();
 const sell=await sellResponse;const sellBody=await sell.json();
 await fs.writeFile(path.join(out,'sell-summary.json'),JSON.stringify({status:sell.status(),mode:sellBody.mode,samplePhoto:sellBody.samplePhoto,listing:sellBody.listing,error:sellBody.error},null,2));
 if(sell.status()!==200)throw new Error(`Sell HTTP ${sell.status()}: ${sellBody.error}`);
 await page.getByText('Draft ready for your review.',{exact:true}).waitFor();
 await mark('sample_pipeline_finished',{mode:sellBody.mode,samplePhoto:sellBody.samplePhoto,questions:sellBody.listing.questions_for_owner});
 await page.locator('.media-grid').scrollIntoViewIfNeeded();
 await mark('three_view_comparison_visible');
 await page.waitForTimeout(3000);
 await page.screenshot({path:path.join(out,'02a-three-views.png'),fullPage:false});
 await page.locator('.card.condition').scrollIntoViewIfNeeded();
 await mark('condition_map_visible');
 await page.waitForTimeout(3000);
 await page.screenshot({path:path.join(out,'02b-condition-map.png'),fullPage:false});
 await page.locator('.listing-grid').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(out,'02-desktop-draft.png'),fullPage:false});
 const ownerQuestions=page.locator('.owner-answer input');
 if(await ownerQuestions.count()){
  const labels=await page.locator('.owner-answer span').allInnerTexts();
  const questionIndex=Math.max(0,labels.findIndex(q=>/power|spin|sound|work|function/i.test(q)));
  const question=labels[questionIndex];
  await ownerQuestions.nth(questionIndex).fill('Not tested or verified. Please describe it as unknown.');
  const savedResponse=page.waitForResponse(r=>r.url().endsWith('/api/sell')&&r.request().method()==='PATCH');
  await page.getByRole('button',{name:'Add answers to the listing',exact:true}).click();
  const saved=await savedResponse;if(saved.status()!==200)throw new Error(`Owner update HTTP ${saved.status()}: ${await saved.text()}`);
  await mark('owner_answer_persisted',{question,answer:'Not tested or verified. Please describe it as unknown.'});
 }
 const approvedResponse=page.waitForResponse(r=>r.url().endsWith('/api/sell')&&r.request().method()==='PATCH');
 await page.getByRole('button',{name:'Approve listing in one tap',exact:true}).click();
 const approved=await approvedResponse;if(approved.status()!==200)throw new Error(`Approve HTTP ${approved.status()}`);
 await page.getByRole('button',{name:'Run simulation',exact:true}).waitFor();
 await mark('listing_approved');
 await page.locator('.agent-card').scrollIntoViewIfNeeded();
 const simResponse=page.waitForResponse(r=>r.url().endsWith('/api/simulation'),{timeout:300000});
 await page.getByRole('button',{name:'Run simulation',exact:true}).click();await mark('live_simulation_started');
 const sim=await simResponse;const simBody=await sim.json();
 await fs.writeFile(path.join(out,'simulation-summary.json'),JSON.stringify({status:sim.status(),...simBody},null,2));
 if(sim.status()!==200)throw new Error(`Simulation HTTP ${sim.status()}: ${simBody.error}`);
 await mark('live_simulation_finished',{cards:simBody.dealCards?.length});
 if(!simBody.dealCards?.length)throw new Error('Simulation completed with no decision cards; no acceptance can be demonstrated.');
 await page.locator('.card.inbox').scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(out,'03-desktop-sell-card.png'),fullPage:false});
 await mark('sell_card_review_hold');await page.waitForTimeout(4000);
 const acceptedResponse=page.waitForResponse(r=>r.url().endsWith('/api/inbox')&&r.request().method()==='POST');
 await page.locator('.card.inbox').getByRole('button',{name:'Yes',exact:true}).first().click();
 const accepted=await acceptedResponse;if(accepted.status()!==200)throw new Error(`Accept HTTP ${accepted.status()}`);
 await page.locator('.card.inbox .status-accepted').waitFor();await mark('sell_accepted');
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('.card.inbox .status-accepted').waitFor();await mark('sell_acceptance_survived_reload');
 await page.locator('.card.inbox').scrollIntoViewIfNeeded();await page.waitForTimeout(3000);
 await page.locator('.find-card').scrollIntoViewIfNeeded();
 await page.getByLabel('What are you looking for',{exact:true}).fill('Working toddler bicycle');
 await page.getByLabel('Maximum price in EUR',{exact:true}).fill('100');
 const needResponse=page.waitForResponse(r=>r.url().endsWith('/api/find')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'Save need',exact:true}).click();
 const need=await needResponse;if(need.status()!==200)throw new Error(`Need HTTP ${need.status()}`);
 await page.getByLabel('Seller message',{exact:true}).fill('I am selling a toddler bicycle for EUR 80. The bicycle works correctly and is suitable for toddlers. Pickup is available Saturday at 10:00 in Brno.');
 const offerResponse=page.waitForResponse(r=>r.url().endsWith('/api/find')&&r.request().method()==='POST',{timeout:180000});
 await page.getByRole('button',{name:'Evaluate offer',exact:true}).click();await mark('find_qualification_started');
 const offer=await offerResponse;const offerBody=await offer.json();
 await fs.writeFile(path.join(out,'find-summary.json'),JSON.stringify({status:offer.status(),...offerBody},null,2));
 if(offer.status()!==200)throw new Error(`Offer HTTP ${offer.status()}: ${offerBody.error}`);
 await mark('find_qualification_finished',{offerStatus:offerBody.offer?.status});
 if(offerBody.offer?.status!=='qualified')throw new Error(`Offer is ${offerBody.offer?.status}: ${JSON.stringify(offerBody.offer?.questions)}`);
 await page.locator('.find-card .deal-card').first().scrollIntoViewIfNeeded();
 await page.screenshot({path:path.join(out,'04-desktop-find-card.png'),fullPage:false});
 await mark('find_card_review_hold');await page.waitForTimeout(4000);
 const findDecision=page.waitForResponse(r=>r.url().endsWith('/api/find')&&r.request().method()==='POST');
 await page.locator('.find-card').getByRole('button',{name:'Yes',exact:true}).first().click();
 const decided=await findDecision;if(decided.status()!==200)throw new Error(`Find decision HTTP ${decided.status()}`);
 await page.locator('.find-card .status-accepted').waitFor();await mark('find_accepted');
 await page.reload({waitUntil:'domcontentloaded'});await page.locator('.find-card .status-accepted').waitFor();await mark('find_acceptance_survived_reload');
 await page.locator('.find-card .deal-card').first().scrollIntoViewIfNeeded();await page.waitForTimeout(3000);
 await mark('walkthrough_passed');
}catch(error){await mark('walkthrough_failed',{error:error.message});await page.screenshot({path:path.join(out,'failure.png'),fullPage:false}).catch(()=>{});process.exitCode=1;}
finally{
 await fs.writeFile(path.join(out,'browser-errors.json'),JSON.stringify({errors,requests},null,2));
 await context.close();const videoPath=await video.path();await fs.writeFile(path.join(out,'video-metadata.json'),JSON.stringify({url,videoPath,recordedAt:new Date().toISOString(),elapsedSeconds:(Date.now()-start)/1000,viewport:{width:1280,height:800},audio:false,unmodified:true},null,2));console.log('VIDEO',videoPath);
 await browser.close();
}
